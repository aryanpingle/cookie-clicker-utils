import { writeFileSync } from 'node:fs';
import { Test1 } from '../src/upgrades/index.js';

function transformName(name: string) {
    switch (name) {
        case '78-hour days':
            return 'SEVENTY_EIGHT_HOUR_DAYS';

        case '9th color':
            return 'NINTH_COLOR';

        case 'Some other super-tiny fundamental particle? Probably?':
            return 'SOME_OTHER_SUPER_TINY_FUNDAMENTAL_PARTICLE_PROBABLY';

        case '0-sided dice':
            return 'ZERO_SIDED_DICE';

        case 'Game.Loop':
            return 'GAME_LOOP';

        case 'eval()':
            return 'EVAL';

        case 'Thoughts & prayers':
            return 'THOUGHTS_AND_PRAYERS';

        case 'Sabl&eacute;s':
            return 'SABLES';

        case 'Peanut butter & jelly':
            return 'PEANUT_BUTTER_AND_JELLY';

        default:
            return name
                .toUpperCase()
                .replace(/\s+/g, '_')
                .replace(/['"]/g, '')
                .replace(/&REG;/g, '')
                .replace(/-/g, '_')
                .replace(/64/g, 'SIXTYFOUR_')
                .replace(/FORTUNE_#/g, 'FORTUNE_')
                .replace(/\[OFF\]/g, '_OFF')
                .replace(/\[ON\]/g, '_ON')
                .replace(/[\(\)]/g, '')
                .replace(/[\/]/g, '')
                .replace(/[\.]/g, '')
                .replace(/\+\+/g, '_PLUS_PLUS');
    }
}

const lines = Test1.map((obj) =>
    Object.entries(obj)
        .map(([name, o]) => `    ${transformName(name)} = ${o.id},`)
        .join('\n'),
);

let src = `
// Do not modify. Auto-generated by a script.

export const enum U {
${lines.join('\n\n')}
}
`;

const filename = 'src/upgrades/gen.ts';

writeFileSync(filename, src);
